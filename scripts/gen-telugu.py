"""
Builds the Class 6 Telugu bank — the Lab's first second-language subject.

Follows the Telangana SCERT Class 6 syllabus: పర్యాయపదాలు (synonyms), వర్ణమాల
విభజన (division of the alphabet), వచనాలు (singular and plural), and పఠన బోధ
(reading comprehension).

Two deliberate decisions about the alphabet section:

  * Counts of అచ్చులు differ between textbooks — some teach 16 including the
    obsolete ఌ and ౡ, others teach 14 without them. Those totals are therefore
    NOT keyed as answers. The questions ask which letters belong to a class and
    how the classes are formed, which every textbook agrees on. The two counts
    that are asked — 25 వర్గాక్షరాలు and 3 ఉభయాక్షరాలు — are not in dispute.

  * Questions are written in Telugu, not about Telugu in English. A second
    language is read in its own script or it is not being read at all.

The comprehension passages are written for this bank. They use the passage
grouping already built for English, so a paper draws whole passages rather
than stray questions.

    python3 scripts/gen-telugu.py
"""

import json
from collections import Counter

BANK = []


def Q(chapter, topic, label, question, correct, wrongs, hint, difficulty,
      passage_id=None, passage_title=None, passage=None):
    options = [correct] + list(wrongs)
    assert len(options) == 4, (question, len(options))
    assert len(set(options)) == 4, ("duplicate options", question)
    doc = {
        "grade": 6, "subject": "telugu", "chapter": chapter,
        "topic": topic, "topicLabel": label,
        "question": question, "options": options, "answer": 0,
        "hint": hint, "difficulty": difficulty,
    }
    if passage_id:
        doc.update(passageId=passage_id, passageTitle=passage_title, passage=passage)
    BANK.append(doc)


